// Root build file. Plugins are declared here with apply false so each
// subproject can opt-in via the version catalog without redeclaring versions.
//
// TODO(security review): wire a JVM dependency-vulnerability scanner into
// CI — org.owasp.dependencycheck (or Snyk) on :apps:desktop and :shared.
// The Rust side already has cargo-deny (deny.toml); the Gradle side has
// no equivalent advisory gate today. Deliberately not applied here yet:
// the plugin needs network access to the NVD feed at build time.
plugins {
    alias(libs.plugins.kotlin.multiplatform) apply false
    alias(libs.plugins.kotlin.android) apply false
    alias(libs.plugins.android.application) apply false
    alias(libs.plugins.android.library) apply false
    alias(libs.plugins.compose.multiplatform) apply false
    alias(libs.plugins.compose.compiler) apply false
    alias(libs.plugins.uniffi) apply false
    // Kover applies on the root so we can aggregate JVM coverage across
    // the modules that opt in (`:shared`, `:apps:desktop`).
    alias(libs.plugins.kover)
}

// Security audit 2026-10 — every JVM test task (jvmTest, integrationTest,
// torTest, …) runs the native core against the in-memory test keystore
// instead of the developer's real OS keyring (DPAPI / Keychain / Secret
// Service). CI Linux runners have no Secret Service, so without this the
// core would (correctly) refuse 6-digit test PINs. Stores created under
// this keystore cannot be reopened by another process — test-only.
subprojects {
    tasks.withType<Test>().configureEach {
        environment("BHODL_KEYSTORE", "ephemeral-test")
    }
}

// Aggregate JVM coverage. Run:
//   ./gradlew koverHtmlReport   -> build/reports/kover/html/index.html
//   ./gradlew koverXmlReport    -> build/reports/kover/report.xml (CI-friendly)
//
// Coverage is restricted to JVM source sets only — Native targets
// (mingwX64 / linuxX64 / iOS) are not instrumentable by Kover.
//
// Excluded from the metric:
// - Generated UniFFI bindings (`io.bhodl.ffi.*`) — they are emitted
//   from the Rust contract and re-running coverage on them just
//   tracks which methods we happen to call from Kotlin.
// - Compose Resources (`io.bhodl.shared.resources.*`) — generated by
//   the Compose plugin from the strings.xml.
// - The runtime classes under `uniffi.runtime.*` — generated by the
//   Ubique bindgen.
// - The test-tag holder objects (`*Tags`) — pure declarations with
//   no executable logic.
// - The route markers (`Route.*`) — serialisable data objects with
//   no behaviour to test.
dependencies {
    kover(project(":shared"))
    kover(project(":apps:desktop"))
}

kover {
    reports {
        filters {
            excludes {
                packages(
                    "io.bhodl.ffi",
                    "io.bhodl.shared.resources",
                    "uniffi.runtime",
                )
                classes(
                    "io.bhodl.desktop.screens.*Tags",
                    "io.bhodl.desktop.navigation.Route*",
                )
            }
        }
    }
}
